"""Tier B tables: decision accuracy per arm, with the domain as the unit of analysis.

    python -m tcmfaudit.analyze_decision

The 128 scenarios are not independent. The four replicates of a (domain, true cause) pair
share all cause-side text, and the four true causes of a domain share the crisis, the symptoms
and each other as decoys. So intervals and tests are computed on the 8 domain means. That is
a small n and the intervals are wide; with 8 units the smallest two-sided sign-flip p is 2/256.
"""
from __future__ import annotations

import json
from collections import defaultdict
from pathlib import Path

import numpy as np

from . import AUDIT_ROOT
from .stats import holm, mean_ci, paired_diff

RESULTS = AUDIT_ROOT / "results" / "decision"

CONFIRMATORY = [
    ("tcmf_shipped@oracle", "chain_text@oracle", "H5: production retriever's memories vs the bare chain text"),
]
EXPLORATORY = [
    ("tcmf_paper@oracle", "chain_text@oracle", "H5 with the paper's configuration"),
    ("tcmf_production_block@oracle", "chain_text@oracle", "production prompt block vs clean chain text"),
    ("tcmf_production_block@deployed_graph", "vector", "production end to end (own linker, own prompt) vs vector"),
    ("tcmf_shipped@deployed_graph", "vector", "production retriever on its own linker's graph vs vector"),
    ("tcmf_paper@oracle", "vector", "paper configuration on a perfect graph vs vector"),
    ("tcmf_shipped@oracle", "vector", "production retriever on a perfect graph vs vector"),
    ("tcmf_paper@oracle", "graph_union@oracle", "paper configuration vs the fusion-free graph reader"),
    ("tcmf_paper@wrong_graph", "none", "retrieval steered by a wrong graph vs no memory"),
    ("chain_text@wrong_graph", "none", "wrong chain text vs no memory"),
    ("event_log_union", "vector", "event log without edges vs vector"),
    ("summary", "vector", "rolling summary vs vector"),
    ("chronological", "vector", "sliding window vs vector"),
]

Arms = dict[str, dict[str, list[dict]]]     # arm -> domain -> rows


def load(path: Path) -> dict[bool, Arms]:
    data: dict[bool, Arms] = {False: defaultdict(lambda: defaultdict(list)),
                              True: defaultdict(lambda: defaultdict(list))}
    with path.open(encoding="utf-8") as fh:
        for line in fh:
            row = json.loads(line)
            data[row["link"]][row["arm"]][row["domain"]].append(row)
    return data


def domain_means(by_domain: dict[str, list[dict]], field: str = "correct") -> np.ndarray:
    return np.array([np.mean([r[field] for r in by_domain[d]]) for d in sorted(by_domain)])


def report(path: Path) -> tuple[list[str], dict]:
    data = load(path)
    lines: list[str] = []
    tests: dict[str, dict] = {}
    for link in (False, True):
        arms = data[link]
        label = "link evidence present" if link else "no link evidence (the paper's premise)"
        first = next(iter(arms.values()))
        lines += [f"### {label} (n={sum(len(v) for v in first.values())} scenarios in {len(first)} domains)", "",
                  "| arm | accuracy [95% CI over domains] | root witness shown | gold memories shown | prompt tokens | unparsed |",
                  "|---|---|---|---|---|---|"]
        for arm, by_domain in arms.items():
            mean, lo, hi = mean_ci(domain_means(by_domain))
            flat = [r for rows in by_domain.values() for r in rows]
            lines.append(
                f"| {arm} | {mean:.3f} [{lo:.3f}, {hi:.3f}] | {np.mean([r['root_shown'] for r in flat]):.2f} | "
                f"{np.mean([r['gold_shown'] for r in flat]):.2f} | {np.mean([r['prompt_tokens'] for r in flat]):.0f} | "
                f"{sum(r['unparsed'] for r in flat)} |")
        lines.append("")
        for family, pairs in (("confirmatory", CONFIRMATORY), ("exploratory", EXPLORATORY)):
            for a, b, why in pairs:
                tests[f"link={int(link)} | {a} - {b}"] = {
                    "family": family, "why": why,
                    **paired_diff(domain_means(arms[a]), domain_means(arms[b])),
                }
    adjusted = holm({k: v["p"] for k, v in tests.items() if v["family"] == "confirmatory"})
    lines += ["| comparison (paired over 8 domains) | family | diff | 95% CI | p | Holm p |", "|---|---|---|---|---|---|"]
    for key, t in tests.items():
        t["p_holm"] = adjusted.get(key)
        holm_p = f"{t['p_holm']:.4f}" if t["p_holm"] is not None else "not adjusted"
        lines.append(f"| {key} | {t['family']} | {t['diff']:+.3f} | [{t['lo']:+.3f}, {t['hi']:+.3f}] | {t['p']:.4f} | {holm_p} |")
    return lines + [""], tests


def main() -> None:
    lines = ["# Tier B raw summary", "",
             "Generated by `python -m tcmfaudit.analyze_decision`. Accuracy intervals are percentile "
             "bootstrap over the 8 domain means; tests are sign-flip permutation over domains. Only "
             "the confirmatory pair is Holm-adjusted; exploratory p-values are unadjusted and should "
             "be read as descriptive.", ""]
    all_tests = {}
    for path in sorted(RESULTS.glob("rows_*.jsonl")):
        name = path.stem.removeprefix("rows_")
        section, tests = report(path)
        lines += [f"## {name}", "", *section]
        all_tests[name] = tests
    (RESULTS / "SUMMARY.md").write_text("\n".join(lines), encoding="utf-8")
    (RESULTS / "tests.json").write_text(json.dumps(all_tests, indent=2), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
