"""Linker quality before and after the similarity-only pass over events older than the window.

Runs the production ``CausalGraph.auto_link_predecessors`` on the crisis only, as
``api/sim/engine.py`` does (graph mode ``deployed``), twice per scenario: with its defaults
(the window pass alone, the linker the audit measured in Finding 3) and with
``older_sim_threshold`` set. Synthetic tier: Finding 3's four regimes, seeds 0 to n-1. Text
tier: the 128 Tier B scenarios without link evidence, from the committed embedding caches, so
no model is called.

Each threshold sits just above the highest similarity an unrelated event reached to its crisis
under that encoder. Synthetic: 0.201 over 12,000 pairs from seeds 1000 to 2999, held out from
the seeds measured here. nomic and MiniLM: 0.639 and 0.336 over the 384 unrelated decisions of
the text tier itself, so those two thresholds are fitted on the data they are scored on.

    python -m tcmfaudit.run_linker          # writes results/linker.md
"""
from __future__ import annotations

import argparse
from dataclasses import replace

import numpy as np

from api.memory.causal_graph import OLDER_LINK_THRESHOLD_NOMIC

from . import AUDIT_ROOT, graphs
from . import textworld as T
from .ollama import embed_all
from .world import WorldConfig, generate

OUT = AUDIT_ROOT / "results" / "linker.md"
SYNTHETIC_THRESHOLD = 0.21
TEXT_THRESHOLD = {"nomic-embed-text": OLDER_LINK_THRESHOLD_NOMIC, "all-minilm": 0.34}
REGIMES = [
    ("cause old and unlike the crisis: the paper's premise", (60, 150), 0.0),
    ("cause old, moderately similar (rho 0.5)", (60, 150), 0.5),
    ("cause recent (5 to 40 ticks), unlike the crisis", (5, 40), 0.0),
    ("cause recent and moderately similar", (5, 40), 0.5),
]


def _decoys_linked(anc: dict[int, int], decoys: list[int]) -> float:
    return sum(d in anc for d in decoys) / len(decoys)


def synthetic(n: int, linker: dict | None) -> list[dict]:
    rows = []
    for label, age, rho in REGIMES:
        cfg = replace(WorldConfig(), root_age=age, rho=rho)
        recall, precision, root, decoys = [], [], 0, []
        for seed in range(n):
            world = generate(cfg, seed)
            og = graphs.deployed(world, linker=linker)
            quality = graphs.edge_quality(world, og)
            anc = graphs.ancestors(og)
            recall.append(quality["anc_recall"])
            precision.append(quality["anc_precision"])
            root += (cfg.depth - 1) in anc          # the root is ancestor `depth`, at index depth-1
            decoys.append(_decoys_linked(anc, world.events_of("decoy")))
        rows.append({"regime": label, "found": np.mean(recall), "precision": np.nanmean(precision),
                     "root": root, "decoys": np.mean(decoys)})
    return rows


def text(encoder: str, linker: dict | None) -> dict:
    cache = AUDIT_ROOT / "results" / "decision" / f"emb_{encoder}.json"
    embed = embed_all(T.all_texts(), encoder, cache)
    root = mechanism = 0
    decoys = []
    specs = T.scenario_specs()
    for spec in specs:
        world = T.build(spec, False, embed).world
        anc = graphs.ancestors(graphs.deployed(world, linker=linker))
        root += T.ROOT in anc
        mechanism += T.MECHANISM in anc
        decoys.append(_decoys_linked(anc, world.events_of("decoy")))
    return {"n": len(specs), "root": root, "mechanism": mechanism, "decoys": np.mean(decoys)}


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--n", type=int, default=500)
    args = parser.parse_args()
    after = {"older_sim_threshold": SYNTHETIC_THRESHOLD}
    lines = [
        "# Linker: window pass alone vs window pass plus older similarity-only pass", "",
        f"Generated by `python -m tcmfaudit.run_linker`. Synthetic n = {args.n}, threshold "
        f"{SYNTHETIC_THRESHOLD}, at most 2 older links per crisis. Cells are before / after.", "",
        "| regime | true ancestors found | precision | true root linked | unrelated events linked |",
        "|---|---|---|---|---|",
    ]
    for b, a in zip(synthetic(args.n, None), synthetic(args.n, after)):
        lines.append(
            f"| {b['regime']} | {b['found']:.2f} / {a['found']:.2f} | {b['precision']:.2f} / "
            f"{a['precision']:.2f} | {b['root']} / {a['root']} of {args.n} | "
            f"{b['decoys']:.2f} / {a['decoys']:.2f} |"
        )
    lines += [
        "", "Text tier, 128 scenarios without link evidence. Before / after.", "",
        "| encoder | threshold | root decision linked | mechanism linked | unrelated decisions linked |",
        "|---|---|---|---|---|",
    ]
    for encoder, threshold in TEXT_THRESHOLD.items():
        b = text(encoder, None)
        a = text(encoder, {"older_sim_threshold": threshold})
        lines.append(
            f"| {encoder} | {threshold} | {b['root']} / {a['root']} of {b['n']} | "
            f"{b['mechanism']} / {a['mechanism']} of {b['n']} | {b['decoys']:.2f} / {a['decoys']:.2f} |"
        )
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
